
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "PTW_PRO"."PTW_LV_ATW_V" ("ATW_ID", "ATW_NUMBER", "COMPANY_ID", "SITE_ID", "SITE_NAME", "HOLDER_USER_ID", "HOLDER_USERNAME", "HOLDER_NAME", "HOLDER_EMPLOYER", "HOLDER_MOBILE", "VALID_DATE", "WORK_DESCRIPTION", "RAMS_REFERENCE", "INDUCTION_OK", "SSOW_OK", "COMPETENCE_OK", "EQUIPMENT_PPE_OK", "ISSUER_NOTES", "STATUS", "EFFECTIVE_STATUS", "REQUESTED_BY", "REQUESTED_DATETIME", "ISSUED_BY", "ISSUER_NAME", "ISSUED_DATETIME", "CHECK_IN_DATETIME", "CHECK_OUT_DATETIME", "REVOKED_BY", "REVOKED_DATETIME", "REVOKE_REASON", "EXPIRED_DATETIME", "NOT_CHECKED_OUT", "VERIFY_TOKEN", "CREATED_DATE", "CREATED_BY", "MODIFIED_DATE", "MODIFIED_BY") AS
  SELECT a.atw_id,
       a.atw_number,
       a.company_id,
       a.site_id,
       s.site_name,
       a.holder_user_id,
       UPPER(u.username)                                        AS holder_username,
       a.holder_name,
       a.holder_employer,
       a.holder_mobile,
       a.valid_date,
       a.work_description,
       a.rams_reference,
       a.induction_ok,
       a.ssow_ok,
       a.competence_ok,
       a.equipment_ppe_ok,
       a.issuer_notes,
       a.status,
       ptw_pro.ptw_atw_pkg.effective_status(a.status, a.valid_date) AS effective_status,
       a.requested_by,
       a.requested_datetime,
       a.issued_by,
       a.issuer_name,
       a.issued_datetime,
       a.check_in_datetime,
       a.check_out_datetime,
       a.revoked_by,
       a.revoked_datetime,
       a.revoke_reason,
       a.expired_datetime,
       a.not_checked_out,
       a.verify_token,
       a.created_date,
       a.created_by,
       a.modified_date,
       a.modified_by
FROM   ptw_pro.ptw_lv_atw   a
JOIN   ptw_pro.ptw_lv_sites s ON s.site_id = a.site_id
JOIN   ptw_pro.ptw_lv_users u ON u.user_id = a.holder_user_id;
